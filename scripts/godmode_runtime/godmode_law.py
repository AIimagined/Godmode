"""Sprint L1 of the Code of Law loop: the writer and the slot.

The operator's ask (request 4110, decision 4114): do for every project what
a hand-maintained rules file does for one - a per-project law file, fired at
session start on every host, maintained by godmode itself. L1 is the writer
and the slot: `law compile` folds every lesson that carries a generalized
guard into a bounded `GODMODE-CODE-OF-LAW.md` with provenance, a wrapper
skill carries it to hook-less hosts, the file is a bound authority role so
the charter, `attest` and the required-sources counter consume it with no
new machinery, and the SessionStart brief carries the top laws.

Doctrine constraints, live in this module:
- The file is GENERATED and says so; a hand edit is overwritten. The hand
  file this generalizes rotted exactly because nothing regenerated it.
- Bounded, and the bound is stated in the artifact (no silent caps): laws
  beyond the cap are counted in the file itself.
- Deterministic: same archive, same bytes - no timestamps, no randomness -
  so `bindings`-style drift checks and git diffs stay meaningful.
- Counts and reviewed prose only. A lesson's value and guard were written
  at recording time under the archive's own secret scan; nothing here reads
  prompts or source bodies.

Detectors, receipts and the promotion ladder are L2/L3 (see the spec);
until then every compiled law is ADVISORY and its provenance is the lesson
it came from.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Any

LAW_FILENAME = "GODMODE-CODE-OF-LAW.md"
SKILL_DIRNAME = "godmode-code-of-law"
LAW_CAP = 24
GUARD_CHARS = 200
WHY_CHARS = 160

_HEADER = f"""# GODMODE CODE OF LAW

Generated by `godmode law compile` from this project's archive. Do not
hand-edit: the next compile overwrites this file. Each law is a lesson this
project recorded with a generalized guard; the sequence number is its
provenance in the hash-chained archive (`godmode slice`/`history` to read
it back). Laws are ADVISORY until the promotion ladder ships; follow the
guard, and when a guard is wrong, retire the lesson rather than ignoring
the law.
"""


def _ellipsize(text: str, limit: int) -> str:
    flattened = " ".join(str(text).split())
    if len(flattened) <= limit:
        return flattened
    return flattened[: limit - 1].rstrip() + "…"


def _guarded_lessons(archive: Any) -> list[dict[str, Any]]:
    # Dedup by subject, newest record wins (2026-08-29): a promotion retried
    # after a parse error wrote the same law twice, and two 2026-08-11
    # lessons had shared a subject since before the compiler existed - each
    # rendered as its own law. One subject, one law, and appending a
    # retired record now actually retires the law (the newest record is the
    # subject's state, the same rule status remaining already follows).
    by_subject: dict[str, dict[str, Any]] = {}
    for record in archive.read_events():
        if record.get("kind") != "lesson":
            continue
        current = by_subject.get(str(record.get("subject", "")))
        if current is None or int(record.get("sequence", 0)) > current["sequence"]:
            by_subject[str(record.get("subject", ""))] = {
                "sequence": int(record.get("sequence", 0)), "record": record}
    lessons = []
    for kept in by_subject.values():
        record = kept["record"]
        data = record.get("data") or {}
        if str(data.get("status", "active")) in ("retired", "candidate"):
            continue
        guard = str(data.get("generalized_guard") or "").strip()
        if not guard:
            continue
        lessons.append({
            "sequence": int(record.get("sequence", 0)),
            "subject": str(record.get("subject", ""))[:120],
            "guard": guard,
            "why": str(data.get("value", "")),
            "recorded_at": str(record.get("recorded_at", ""))[:10],
        })
    lessons.sort(key=lambda lesson: lesson["sequence"], reverse=True)
    return lessons


def _delivered_seqs(archive: Any) -> set[int]:
    delivered: set[int] = set()
    for record in archive.read_events():
        if record.get("kind") == "action" and record.get("subject") == "laws-delivered":
            for seq in (record.get("data") or {}).get("law_seqs") or []:
                delivered.add(int(seq))
    return delivered


def top_laws(archive: Any, k: int) -> list[dict[str, Any]]:
    """The k newest laws, bounded for the brief's budget. `dormant` means no
    delivery receipt has ever named this law - L3's decay input, flagged
    rather than silently carried."""
    delivered = _delivered_seqs(archive)
    return [
        {"subject": lesson["subject"], "guard": _ellipsize(lesson["guard"], GUARD_CHARS),
         "seq": lesson["sequence"], "dormant": lesson["sequence"] not in delivered}
        for lesson in _guarded_lessons(archive)[: max(0, k)]
    ]


def _render(laws: list[dict[str, Any]], dropped: int, cap: int) -> str:
    lines = [_HEADER]
    for number, lesson in enumerate(laws, 1):
        lines.append(f"## Law {number} - {lesson['subject']}  [ADVISORY]")
        lines.append(f"Guard: {_ellipsize(lesson['guard'], GUARD_CHARS)}")
        lines.append(f"Why: {_ellipsize(lesson['why'], WHY_CHARS)}")
        lines.append(
            f"Provenance: seq:{lesson['sequence']}, recorded {lesson['recorded_at']}")
        lines.append("")
    if dropped:
        lines.append(
            f"{dropped} older guarded lesson(s) beyond the cap of {cap} are not "
            "rendered here - raise the cap, or retire laws that no longer earn "
            "their place.")
        lines.append("")
    return "\n".join(lines)


